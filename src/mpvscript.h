#ifndef CWATCH_MPVSCRIPT_H
#define CWATCH_MPVSCRIPT_H

static const char MPV_SCRIPT[] =
"local mode = os.getenv('CWATCH_MODE') or 'local'\n"
"local next_label = os.getenv('CWATCH_NEXT') or ''\n"
"local state = os.getenv('CWATCH_STATE') or ''\n"
"local track_key = os.getenv('CWATCH_TRACKKEY') or ''\n"
"local ep_key = os.getenv('CWATCH_EPKEY') or ''\n"
"local at = 90\n"
"local ov = mp.create_osd_overlay('ass-events')\n"
"ov.res_x, ov.res_y = 1280, 720\n"
"local visible, ready, marked = false, false, false\n"
"local cur_path = ''\n"
"local box = {x1 = 920, y1 = 560, x2 = 1220, y2 = 620}\n"
"\n"
"local function has_next()\n"
"  if mode == 'stream' then return next_label ~= '' end\n"
"  local pos = mp.get_property_number('playlist-pos', 0)\n"
"  return pos + 1 < mp.get_property_number('playlist-count', 1)\n"
"end\n"
"\n"
"local function label()\n"
"  if mode == 'stream' then return next_label end\n"
"  local pos = mp.get_property_number('playlist-pos', 0)\n"
"  return mp.get_property('playlist/' .. (pos + 1) .. '/title', '')\n"
"end\n"
"\n"
"local function mark_watched()\n"
"  if marked or state == '' then return end\n"
"  marked = true\n"
"  local key = mode == 'stream' and ep_key or cur_path\n"
"  if key == '' then return end\n"
"  local f = io.open(state .. '/watched_auto.txt', 'a')\n"
"  if f then f:write(key .. '\\n') f:close() end\n"
"end\n"
"\n"
"local function go_next()\n"
"  if not has_next() then return end\n"
"  mark_watched()\n"
"  if mode == 'stream' then mp.command('quit 42') else mp.command('playlist-next force') end\n"
"end\n"
"\n"
"local function click()\n"
"  local x, y = mp.get_mouse_pos()\n"
"  local w, h = mp.get_osd_size()\n"
"  if not w or w == 0 or h == 0 then return end\n"
"  x, y = x * 1280 / w, y * 720 / h\n"
"  if x >= box.x1 and x <= box.x2 and y >= box.y1 and y <= box.y2 then go_next() end\n"
"end\n"
"\n"
"local function hide()\n"
"  if not visible then return end\n"
"  visible = false\n"
"  ov:remove()\n"
"  mp.remove_key_binding('cwatch-click')\n"
"end\n"
"\n"
"local function show()\n"
"  if visible then return end\n"
"  visible = true\n"
"  local d = string.format('{\\\\an7\\\\pos(%d,%d)\\\\bord0\\\\shad0\\\\1c&HFFFFFF&\\\\p1}m 0 0 l 300 0 l 300 60 l 0 60{\\\\p0}', box.x1, box.y1)\n"
"  d = d .. string.format('\\n{\\\\an4\\\\pos(%d,%d)\\\\fs30\\\\b1\\\\bord0\\\\shad0\\\\1c&H000000&}Next Episode  (N)', box.x1 + 30, box.y1 + 30)\n"
"  local l = label()\n"
"  if l ~= '' then\n"
"    d = d .. string.format('\\n{\\\\an3\\\\pos(%d,%d)\\\\fs22\\\\bord2\\\\shad0\\\\1c&HFFFFFF&\\\\3c&H000000&}%s', box.x2, box.y1 - 10, l)\n"
"  end\n"
"  ov.data = d\n"
"  ov:update()\n"
"  mp.add_key_binding('MBTN_LEFT', 'cwatch-click', click)\n"
"end\n"
"\n"
"local function read_prefs()\n"
"  if state == '' or track_key == '' then return nil end\n"
"  local f = io.open(state .. '/tracks/' .. track_key, 'r')\n"
"  if not f then return nil end\n"
"  local p = {}\n"
"  for line in f:lines() do\n"
"    local k, v = line:match('^(%w+)=(.*)$')\n"
"    if k then p[k] = v end\n"
"  end\n"
"  f:close()\n"
"  return p\n"
"end\n"
"\n"
"local function track(kind, id)\n"
"  if type(id) ~= 'number' then return nil end\n"
"  for _, t in ipairs(mp.get_property_native('track-list', {})) do\n"
"    if t.type == kind and t.id == id then return t end\n"
"  end\n"
"end\n"
"\n"
"local function save_prefs()\n"
"  if not ready or state == '' or track_key == '' then return end\n"
"  local aid, sid = mp.get_property_native('aid'), mp.get_property_native('sid')\n"
"  local a, s = track('audio', aid), track('sub', sid)\n"
"  if (type(aid) == 'number' and not a) or (type(sid) == 'number' and not s) then return end\n"
"  os.execute(\"mkdir -p '\" .. state .. \"/tracks'\")\n"
"  local f = io.open(state .. '/tracks/' .. track_key, 'w')\n"
"  if not f then return end\n"
"  if a then f:write('alang=' .. (a.lang or '') .. '\\natitle=' .. (a.title or '') .. '\\n') end\n"
"  if s then f:write('slang=' .. (s.lang or '') .. '\\nstitle=' .. (s.title or '') .. '\\nsforced=' .. (s.forced and 'yes' or 'no') .. '\\n')\n"
"  else f:write('slang=no\\n') end\n"
"  f:close()\n"
"end\n"
"\n"
"local iso = {eng='en', jpn='ja', spa='es', ger='de', deu='de', fre='fr', fra='fr', ita='it', por='pt', rus='ru', rum='ro', ron='ro', chi='zh', zho='zh', kor='ko', ara='ar'}\n"
"local function norm(l)\n"
"  l = (l or ''):lower():gsub('[-_].*', '')\n"
"  return iso[l] or l\n"
"end\n"
"\n"
"local function partial(t)\n"
"  local s = (t or ''):lower()\n"
"  return s:find('sign') or s:find('song') or s:find('forced') or s:find('forzado')\n"
"end\n"
"\n"
"local function pick(kind, lang, title, forced)\n"
"  local best, fallback\n"
"  local want_partial = forced == 'yes' or partial(title)\n"
"  for _, t in ipairs(mp.get_property_native('track-list', {})) do\n"
"    if t.type == kind and norm(t.lang) == norm(lang) then\n"
"      if (t.title or '') == title then return t.id end\n"
"      local p = t.forced or partial(t.title)\n"
"      if not best and (kind ~= 'sub' or (p and true or false) == (want_partial and true or false)) then best = t.id end\n"
"      fallback = fallback or t.id\n"
"    end\n"
"  end\n"
"  return best or fallback\n"
"end\n"
"\n"
"local function apply_prefs()\n"
"  cur_path = mp.get_property('path', '')\n"
"  local p = read_prefs()\n"
"  if p then\n"
"    if p.alang then\n"
"      local id = pick('audio', p.alang, p.atitle or '', nil)\n"
"      if id then mp.set_property_number('aid', id) end\n"
"    end\n"
"    if p.slang == 'no' then mp.set_property('sid', 'no')\n"
"    elseif p.slang then\n"
"      local id = pick('sub', p.slang, p.stitle or '', p.sforced)\n"
"      if id then mp.set_property_number('sid', id) end\n"
"    end\n"
"  end\n"
"  mp.add_timeout(1.0, function() ready = true end)\n"
"end\n"
"\n"
"mp.register_event('start-file', function() ready = false marked = false hide() end)\n"
"mp.register_event('end-file', function(e)\n"
"  ready = false\n"
"  if e.reason == 'eof' then mark_watched() end\n"
"  if os.getenv('CWATCH_DRYRUN') then mp.command('quit') end\n"
"end)\n"
"mp.register_event('file-loaded', apply_prefs)\n"
"mp.observe_property('aid', 'native', save_prefs)\n"
"mp.observe_property('sid', 'native', save_prefs)\n"
"mp.add_key_binding('n', 'cwatch-next', go_next)\n"
"mp.observe_property('percent-pos', 'number', function(_, p) if p and p >= 90 then mark_watched() end end)\n"
"mp.observe_property('time-remaining', 'number', function(_, t)\n"
"  if t and t > 0 and t <= at and has_next() then show() else hide() end\n"
"end)\n"
"mp.observe_property('eof-reached', 'bool', function(_, eof)\n"
"  if not eof or mode ~= 'stream' then return end\n"
"  mark_watched()\n"
"  mp.set_property('save-position-on-quit', 'no')\n"
"  mp.command('delete-watch-later-config')\n"
"  if has_next() then mp.command('quit 42') else mp.command('quit') end\n"
"end)\n";

#endif
